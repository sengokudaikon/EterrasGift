//! `cargo xtask phrases [--check]`: every word the app shows, in one gettext template, `lang/eterras-gift.pot`, for
//! translators. Two sources, one msgid space without contexts: each `Phrase::new("…")` in the crates' sources (up to
//! a file's `#[cfg(test)]`), and each `@tr` in the views, read by `slint-tr-extractor`. References name the file only,
//! so moving code does not make the template stale; the header carries no date, so `--check` compares as written.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const TEMPLATE: &str = "lang/eterras-gift.pot";
const NEWLINE: &str = "\r\n";

/// One msgid with where it comes from.
#[derive(Default)]
struct Entry {
    plural: Option<String>,
    files: Vec<String>,
}

pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let mut entries: BTreeMap<String, Entry> = BTreeMap::new();
    let mut add = |msgid: String, plural: Option<String>, file: String| {
        let entry = entries.entry(msgid).or_default();
        entry.plural = entry.plural.take().or(plural);
        if !entry.files.contains(&file) {
            entry.files.push(file);
        }
    };
    let mut sources = Vec::new();
    rust_files(&root.join("crates"), &mut sources)?;
    sources.sort();
    for path in &sources {
        let file = relative(root, path);
        let text = fs::read_to_string(path).map_err(|e| format!("{path:?}: {e}"))?;
        // Comments only talk about phrases.
        let text: String = text
            .split("#[cfg(test)]")
            .next()
            .unwrap_or_default()
            .lines()
            .filter(|line| !line.trim_start().starts_with("//"))
            .collect::<Vec<_>>()
            .join(
                "
",
            );
        let text = text.as_str();
        for msgid in rust_phrases(text).map_err(|e| format!("{file}: {e}"))? {
            add(msgid, None, file.clone());
        }
    }
    for (msgid, plural, file) in view_phrases(root)? {
        add(msgid, plural, file);
    }

    // Grouped by where each first appears, so a page's words sit together.
    let mut ordered: Vec<(&String, &Entry)> = entries.iter().collect();
    ordered.sort_by(|a, b| (&a.1.files[0], a.0).cmp(&(&b.1.files[0], b.0)));
    let mut out = String::new();
    let mut line = |text: &str| {
        out.push_str(text);
        out.push_str(NEWLINE);
    };
    line("# Eterra's Gift: the words it shows. Generated by `cargo xtask phrases`; do not edit.");
    line("msgid \"\"");
    line("msgstr \"\"");
    line("\"Project-Id-Version: Eterra's Gift\\n\"");
    line("\"MIME-Version: 1.0\\n\"");
    line("\"Content-Type: text/plain; charset=UTF-8\\n\"");
    line("\"Content-Transfer-Encoding: 8bit\\n\"");
    line("\"Plural-Forms: nplurals=2; plural=(n != 1);\\n\"");
    for (msgid, entry) in ordered {
        line("");
        line(&format!("#: {}", entry.files.join(" ")));
        line(&format!("msgid {}", quote(msgid)));
        match &entry.plural {
            Some(plural) => {
                line(&format!("msgid_plural {}", quote(plural)));
                line("msgstr[0] \"\"");
                line("msgstr[1] \"\"");
            }
            None => line("msgstr \"\""),
        }
    }

    let path = root.join(TEMPLATE);
    let current = fs::read_to_string(&path).ok();
    if check {
        return if current.as_deref() == Some(out.as_str()) {
            Ok(())
        } else {
            Err(format!("{TEMPLATE} is out of date, run `cargo xtask phrases`"))
        };
    }
    fs::create_dir_all(path.parent().unwrap()).map_err(|e| e.to_string())?;
    fs::write(&path, &out).map_err(|e| format!("{path:?}: {e}"))?;
    println!(
        "wrote {TEMPLATE} ({} phrases{})",
        entries.len(),
        if current.as_deref() == Some(out.as_str()) { ", unchanged" } else { "" }
    );
    Ok(())
}

fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), String> {
    for entry in fs::read_dir(dir).map_err(|e| format!("{dir:?}: {e}"))? {
        let path = entry.map_err(|e| e.to_string())?.path();
        let name = path.file_name().and_then(|name| name.to_str()).unwrap_or_default();
        if path.is_dir() {
            // Tests, benches and the tasks themselves show the user nothing.
            if !matches!(name, "tests" | "benches" | "target" | "xtask") {
                rust_files(&path, out)?;
            }
        } else if name.ends_with(".rs") && !name.ends_with("_tests.rs") {
            out.push(path);
        }
    }
    Ok(())
}

fn relative(root: &Path, path: &Path) -> String {
    path.strip_prefix(root).unwrap_or(path).to_string_lossy().replace('\\', "/")
}

/// The English of each `Phrase::new("…")`: one plain or raw string literal, as the type's docs ask.
fn rust_phrases(text: &str) -> Result<Vec<String>, String> {
    let mut found = Vec::new();
    let mut rest = text;
    while let Some(at) = rest.find("Phrase::new(") {
        rest = rest[at + "Phrase::new(".len()..].trim_start();
        let (literal, after) = rust_literal(rest).ok_or_else(|| format!("Phrase::new without a string literal near {:?}", &rest[..rest.len().min(40)]))?;
        found.push(literal);
        rest = after;
    }
    Ok(found)
}

/// A Rust string literal at the start of `text`, unescaped, and what follows it.
fn rust_literal(text: &str) -> Option<(String, &str)> {
    if let Some(raw) = text.strip_prefix('r') {
        let hashes = raw.len() - raw.trim_start_matches('#').len();
        let body = raw[hashes..].strip_prefix('"')?;
        let close = format!("\"{}", "#".repeat(hashes));
        let end = body.find(&close)?;
        return Some((body[..end].to_owned(), &body[end + close.len()..]));
    }
    let body = text.strip_prefix('"')?;
    let mut out = String::new();
    let mut chars = body.char_indices();
    while let Some((at, c)) = chars.next() {
        match c {
            '"' => return Some((out, &body[at + 1..])),
            '\\' => match chars.next()?.1 {
                'n' => out.push('\n'),
                't' => out.push('\t'),
                'r' => out.push('\r'),
                '0' => out.push('\0'),
                'u' => {
                    let digits: String = chars.by_ref().map(|(_, c)| c).skip(1).take_while(|c| *c != '}').collect();
                    out.push(char::from_u32(u32::from_str_radix(&digits, 16).ok()?)?);
                }
                // A line continuation: the break and the next line's indent are not part of the string.
                '\n' | '\r' => {
                    let tail = &body[at + 1..];
                    let skipped = tail.len() - tail.trim_start().len();
                    for _ in 0..tail[..skipped].chars().count() - 1 {
                        chars.next();
                    }
                }
                other => out.push(other),
            },
            c => out.push(c),
        }
    }
    None
}

/// The views' `@tr` strings, as `slint-tr-extractor` reads them, with the file each is in.
fn view_phrases(root: &Path) -> Result<Vec<(String, Option<String>, String)>, String> {
    let mut views = Vec::new();
    slint_files(&root.join("crates/ui/ui"), &mut views)?;
    views.sort();
    let output = std::env::temp_dir().join(format!("eg-phrases-{}.pot", std::process::id()));
    let status = Command::new("slint-tr-extractor")
        .current_dir(root)
        .arg("--no-default-translation-context")
        .arg("-o")
        .arg(&output)
        .args(views.iter().map(|path| relative(root, path)))
        .status()
        .map_err(|e| format!("slint-tr-extractor (1.18.1, in %USERPROFILE%\\.local\\bin) could not run: {e}"));
    let text = fs::read_to_string(&output);
    let _ = fs::remove_file(&output);
    if !status?.success() {
        return Err("slint-tr-extractor failed".into());
    }
    let text = text.map_err(|e| format!("{output:?}: {e}"))?;
    let mut found = Vec::new();
    for block in text.replace("\r\n", "\n").split("\n\n") {
        let mut file = None;
        let mut fields: BTreeMap<&str, String> = BTreeMap::new();
        let mut current = None;
        for line in block.lines() {
            if let Some(reference) = line.strip_prefix("#: ") {
                file = reference.split_whitespace().next().map(|at| at.rsplit_once(':').map_or(at, |(path, _)| path).to_owned());
            } else if let Some((key, value)) = line.split_once(' ').filter(|(key, _)| matches!(*key, "msgid" | "msgid_plural" | "msgctxt")) {
                fields.insert(key, po_string(value)?);
                current = Some(key);
            } else if line.starts_with('"') {
                if let Some(key) = current {
                    let more = po_string(line)?;
                    fields.entry(key).or_default().push_str(&more);
                }
            } else {
                current = None;
            }
        }
        if fields.contains_key("msgctxt") {
            return Err(format!("a view's @tr has a context; the catalog has none: {block}"));
        }
        if let (Some(msgid), Some(file)) = (fields.remove("msgid"), file)
            && !msgid.is_empty()
        {
            found.push((msgid, fields.remove("msgid_plural"), file));
        }
    }
    Ok(found)
}

fn slint_files(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), String> {
    for entry in fs::read_dir(dir).map_err(|e| format!("{dir:?}: {e}"))? {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.is_dir() {
            slint_files(&path, out)?;
        } else if path.extension().is_some_and(|ext| ext == "slint") {
            out.push(path);
        }
    }
    Ok(())
}

/// A quoted PO string, unescaped.
fn po_string(quoted: &str) -> Result<String, String> {
    let body = quoted
        .trim()
        .strip_prefix('"')
        .and_then(|s| s.strip_suffix('"'))
        .ok_or_else(|| format!("not a PO string: {quoted}"))?;
    let mut out = String::new();
    let mut chars = body.chars();
    while let Some(c) = chars.next() {
        if c == '\\' {
            match chars.next() {
                Some('n') => out.push('\n'),
                Some('t') => out.push('\t'),
                Some(other) => out.push(other),
                None => return Err(format!("a PO string ends in a backslash: {quoted}")),
            }
        } else {
            out.push(c);
        }
    }
    Ok(out)
}

/// A PO string literal; a msgid with line breaks is split after each, as gettext's tools write it.
fn quote(text: &str) -> String {
    let escape = |s: &str| s.replace('\\', "\\\\").replace('"', "\\\"").replace('\t', "\\t").replace('\n', "\\n");
    if !text.contains('\n') || text.ends_with('\n') && text.matches('\n').count() == 1 {
        return format!("\"{}\"", escape(text));
    }
    let mut out = String::from("\"\"");
    for piece in text.split_inclusive('\n') {
        out.push_str(NEWLINE);
        out.push_str(&format!("\"{}\"", escape(piece)));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rust_literals_unescape_as_rust_does() {
        assert_eq!(rust_phrases(r#"const A: Phrase = Phrase::new("Say \"hi\"\n{name}");"#).unwrap(), ["Say \"hi\"\n{name}"]);
        assert_eq!(rust_phrases("Phrase::new(\"one \\\n        two\")").unwrap(), ["one two"]);
        assert_eq!(rust_phrases(r###"Phrase::new(r#"raw "quoted""#)"###).unwrap(), ["raw \"quoted\""]);
        assert_eq!(rust_phrases(r#"Phrase::new("T1\u{a0}only")"#).unwrap(), ["T1\u{a0}only"]);
        assert!(rust_phrases("Phrase::new(NAME)").is_err());
    }

    #[test]
    fn po_strings_round_trip() {
        for text in ["plain", "with \"quotes\" and \\", "two\nlines", "ends\n"] {
            let quoted = quote(text);
            let joined: String = quoted.split(NEWLINE).map(|piece| po_string(piece).unwrap()).collect();
            assert_eq!(joined, text);
        }
    }
}
